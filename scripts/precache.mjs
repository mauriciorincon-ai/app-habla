// Pure core of the generated precache (S15, ADR-027). No I/O here: gen-precache.mjs feeds it the
// build output, the unit test feeds it fixtures.
//
// PRIVACY (hard rule 2): the list only ever holds the app's own public files (HTML routes, hashed
// chunks, worklets, pictograms, icons). Audio, the recognizer models and engine (/modelos/, /vosk/)
// and anything else are refused here, so the service worker can never be told to cache them.

/** The routes a family must be able to open offline after the first visit to `/`. */
export const RUTAS_SIN_RED = [
  "/",
  "/jugar",
  "/jugar/globo",
  "/jugar/cohete",
  "/jugar/palabras",
  "/jugar/gemelas",
  "/jugar/soplar",
  "/jugar/fuerte-suave",
  "/jugar/vocales",
  "/cuentos",
  "/ajustes",
];

const CHUNK = /static\/chunks\/[A-Za-z0-9_.-]+\.(?:js|css)/g;
const ESTATICO = /\/_next\/static\/[A-Za-z0-9_./-]+\.(?:js|css|woff2)/g;
const PROHIBIDO = /^\/(?:modelos|vosk)\/|\.(?:wav|mp3|ogg|webm|m4a|aac|opus|mp4|zip|gz)$/i;

/** True when a URL may enter the precache (own public file, never audio or recognizer). */
export function admisible(url) {
  return url.startsWith("/") && !url.startsWith("//") && !PROHIBIDO.test(url);
}

/**
 * Builds the precache list.
 * @param {{ version: string, htmlDeRuta: (ruta: string) => string | null,
 *   leerChunk: (ruta: string) => string | null, extras: string[],
 *   alFaltarHtml?: (ruta: string) => void }} entrada
 *   `alFaltarHtml`: without it a route with no HTML in the build is an error; with it the route is
 *   still listed and the caller decides how to cover its chunks (a host that lays the build out differently).
 * @returns {{ version: string, urls: string[] }}
 */
export function listaPrecache({ version, htmlDeRuta, leerChunk, extras, alFaltarHtml }) {
  if (!version) throw new Error("precache: falta la versión del build");
  const urls = new Set();
  const pendientes = [];
  for (const ruta of RUTAS_SIN_RED) {
    const html = htmlDeRuta(ruta);
    if (html === null) {
      if (!alFaltarHtml) throw new Error(`precache: la ruta ${ruta} no tiene HTML en el build`);
      alFaltarHtml(ruta);
      urls.add(ruta);
      continue;
    }
    urls.add(ruta);
    for (const m of html.match(ESTATICO) ?? []) pendientes.push(m);
  }
  // Transitive closure over the chunks: a dynamic import (lazy content, the sensitivity hashes…) is
  // named inside the chunk that loads it, never in the HTML.
  while (pendientes.length > 0) {
    const url = pendientes.pop();
    if (urls.has(url)) continue;
    urls.add(url);
    if (!url.endsWith(".js")) continue;
    const codigo = leerChunk(url);
    if (codigo === null) continue;
    for (const m of codigo.match(CHUNK) ?? []) pendientes.push(`/_next/${m}`);
  }
  for (const e of extras) urls.add(e);
  const lista = [...urls].filter(admisible).sort();
  return { version, urls: lista };
}

/** The file the service worker imports. */
export function scriptPrecache(lista) {
  return `// Generated by scripts/gen-precache.mjs at build time. Do not edit.\nself.HABLA_PRECACHE = ${JSON.stringify(lista)};\n`;
}
